import { readFile } from 'node:fs/promises';
import { join, relative } from 'node:path';

import { expect, it, vi } from 'vitest';

import { initializeRepository } from './gitRepository.js';
import {
  cargoPackage,
  createCrate,
  createNextestTool,
  libraryWith,
  nextestConfig,
  useSharedCargoEnvironment,
} from './nextestHarness.js';

vi.setConfig({ testTimeout: 60_000, hookTimeout: 60_000 });

useSharedCargoEnvironment('nextest-config');

const staleHint = 'Hint: Test results are stale; rerun run_tests on the current inputs.';

const setup = () => {
  const application = createNextestTool();

  const run = (cwd: string) =>
    application.run(cwd, {
      behavior: 'adds',
      testFullName: 'tests::adds',
      files: ['src/lib.rs'],
    });

  return { run, edit: application.edit };
};

it('accepts src/lib.rs for the nextest runner and fires the production checkpoint after a real edit', async ({
  onTestFinished,
}) => {
  const cwd = await createCrate(onTestFinished, 'config', {
    'Cargo.toml': cargoPackage('probe_config'),
    'src/lib.rs': [
      'pub fn adds(a: i32, b: i32) -> i32 { a + b }',
      '',
      libraryWith('    #[test]\n    fn adds() { assert_eq!(super::adds(1, 2), 3); }'),
    ].join('\n'),
    '.pi/tau.json': nextestConfig,
  });

  const application = setup();

  // The first run creates Cargo.lock, which the nextest configuration globs fingerprint. The
  // second run then sees stable inputs, so only the edit to src/lib.rs makes the results stale.
  await application.run(cwd);

  const result = await application.run(cwd);

  expect(result.details).toMatchObject({ kind: 'pass' });

  const patch = await application.edit(
    cwd,
    'src/lib.rs',
    'pub fn doubles(a: i32) -> i32 { a * 2 }\n',
  );

  expect(patch).toEqual({
    content: [
      { type: 'text', text: 'Original result' },
      { type: 'text', text: staleHint },
    ],
  });
});

it("reports a run that rewrites the chosen project's out-of-date Cargo.lock as stale", async ({
  onTestFinished,
}) => {
  const outdatedLock = [
    '# This file is automatically @generated by Cargo.',
    '# It is not intended for manual editing.',
    'version = 4',
    '',
    '[[package]]',
    'name = "probe_renamed"',
    'version = "0.1.0"',
    '',
  ].join('\n');

  const cwd = await createCrate(onTestFinished, 'rewritten-lock', {
    'backend/Cargo.toml': cargoPackage('probe_rewritten_lock'),
    'backend/Cargo.lock': outdatedLock,
    'backend/src/lib.rs': libraryWith('    #[test]\n    fn adds() {}'),
    '.pi/tau.json': JSON.stringify({
      tdd: { runner: 'nextest', cargoManifestPath: 'backend/Cargo.toml' },
    }),
  });

  const result = await createNextestTool().run(cwd, {
    testFullName: 'tests::adds',
    files: ['backend/src/lib.rs'],
  });

  expect(result.details).toMatchObject({ kind: 'pass', freshness: 'stale' });
  expect(await readFile(join(cwd, 'backend', 'Cargo.lock'), 'utf8')).not.toBe(outdatedLock);
});

it.for([
  { name: 'a default run from a member session', workspace: '', session: 'pkg_b' },
  {
    name: 'a run of a chosen member manifest',
    workspace: 'backend',
    session: '',
    manifest: 'backend/pkg_b/Cargo.toml',
  },
])(
  'reports $name that rewrites the workspace Cargo.lock as stale',
  async ({ workspace, session, manifest }, { onTestFinished }) => {
    const outdatedLock = [
      '# This file is automatically @generated by Cargo.',
      '# It is not intended for manual editing.',
      'version = 4',
      '',
      '[[package]]',
      'name = "probe_renamed"',
      'version = "0.1.0"',
      '',
    ].join('\n');

    const tdd =
      manifest === undefined
        ? { runner: 'nextest' }
        : { runner: 'nextest', cargoManifestPath: manifest };

    const repository = await createCrate(onTestFinished, 'workspace-lock', {
      [join(workspace, 'Cargo.toml')]: '[workspace]\nresolver = "2"\nmembers = ["pkg_b"]\n',
      [join(workspace, 'Cargo.lock')]: outdatedLock,
      [join(workspace, 'pkg_b/Cargo.toml')]: cargoPackage('probe_workspace_lock'),
      [join(workspace, 'pkg_b/src/lib.rs')]: libraryWith('    #[test]\n    fn adds() {}'),
      [join(session, '.pi/tau.json')]: JSON.stringify({ tdd }),
    });

    await initializeRepository(repository);

    const sessionDirectory = join(repository, session);
    const testFile = relative(sessionDirectory, join(repository, workspace, 'pkg_b/src/lib.rs'));

    const result = await createNextestTool().run(sessionDirectory, {
      testFullName: 'tests::adds',
      files: [testFile],
    });

    expect(result.details).toMatchObject({ kind: 'pass', freshness: 'stale' });

    expect(await readFile(join(repository, workspace, 'Cargo.lock'), 'utf8')).not.toBe(
      outdatedLock,
    );
  },
);
